#!/usr/bin/env python3
"""Bake the GBAdhoc wordmark for the PS Vita: gpsp/vita/video_vita_logo.h.

    python3 gpsp/vita/host/bake_logo_2x.py            -> writes the header
    python3 gpsp/vita/host/bake_logo_2x.py --check    -> exit 1 if it differs

The PSP draws the wordmark from psp/logo_ui.h: tools/bake_logo.py's
grid-snapped bake at a 4 px stroke, 151x24, sampled 1:1.  The Vita's screen
is exactly 2x the PSP's, so this is the SAME bake (tools/logo/logomark.py,
render_letters(hint=True)) at an 8 px stroke: every stem 8 px on whole native
pixels, cap / x-height / baseline on whole rows.  It comes out 303x49 -- one
native pixel wider and taller than 2 x (151x24), because the hinted grid
rounds per stem -- and video_vita.c draws it 1:1 at (2x, 2y), nearest.
Stored as 8-bit coverage and tinted by the theme at draw time, like the text.
Requires numpy and Pillow (as tools/bake_logo.py does).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GPSP = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(GPSP, 'tools', 'logo'))
import logomark as M  # noqa: E402

OUT = os.path.join(GPSP, 'vita', 'video_vita_logo.h')
STROKE_PX = 8


def render():
    cov, _ = M.render_letters(stroke_px=STROKE_PX, hint=True)
    h, w = cov.shape
    data = bytes((cov * 255 + 0.5).astype('uint8').tobytes())
    out = ['/* GENERATED by gpsp/vita/host/bake_logo_2x.py -- do not edit.\n'
           ' *\n'
           ' * The GBAdhoc wordmark at the Vita\'s native resolution: the PSP\'s\n'
           ' * grid-snapped bake (tools/logo/logomark.py) at an %d px stroke,\n'
           ' * %dx%d, 8-bit coverage, tinted at draw time. */\n'
           '#ifndef VIDEO_VITA_LOGO_H\n#define VIDEO_VITA_LOGO_H\n\n'
           '#define VV_LOGO_W %d\n#define VV_LOGO_H %d\n\n'
           'static const unsigned char vv_logo_a[%d] = {\n'
           % (STROKE_PX, w, h, w, h, len(data))]
    for i in range(0, len(data), 32):
        out.append(''.join('%d,' % b for b in data[i:i + 32]) + '\n')
    out.append('};\n\n#endif /* VIDEO_VITA_LOGO_H */\n')
    return ''.join(out), w, h


def main(argv):
    text, w, h = render()
    if '--check' in argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('video_vita_logo.h %s' % ('reproduces' if same else 'DIFFERS'))
        return 0 if same else 1
    open(OUT, 'w', newline='\n').write(text)
    print('wrote %s (%dx%d)' % (os.path.relpath(OUT, GPSP), w, h))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
