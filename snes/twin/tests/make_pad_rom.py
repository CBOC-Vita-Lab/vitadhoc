"""Writes a tiny LoROM that enables auto-joypad read and keeps copying
$4218-$421F into battery RAM ($700001..$700008). Test cartridge for pads 1-4."""
import sys
rom = bytearray(0x8000)
code = bytes([0x78, 0x18, 0xFB, 0xA9, 0x01, 0x8D, 0x00, 0x42,
              0xA2, 0x00, 0xBD, 0x18, 0x42, 0x9F, 0x01, 0x00, 0x70,
              0xE8, 0xE0, 0x08, 0xD0, 0xF4, 0x4C, 0x08, 0x80])
rom[0:len(code)] = code
h = 0x7FC0
rom[h:h + 21] = b"PAD TEST ROM         "
rom[h + 0x15] = 0x20; rom[h + 0x16] = 0x02; rom[h + 0x17] = 0x05
rom[h + 0x18] = 0x01; rom[h + 0x19] = 0x01; rom[h + 0x1A] = 0x33
rom[0x7FFC], rom[0x7FFD] = 0, 0x80
s = sum(rom) & 0xFFFF
rom[h + 0x1E], rom[h + 0x1F] = s & 0xFF, s >> 8
c = s ^ 0xFFFF
rom[h + 0x1C], rom[h + 0x1D] = c & 0xFF, c >> 8
open(sys.argv[1], "wb").write(rom)
