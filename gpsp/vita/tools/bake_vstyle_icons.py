#!/usr/bin/env python3
"""bake_vstyle_icons.py -- vstyle_art.py's icons, wordmark and mark -> vstyle_icons.h

    python3 tools/bake_vstyle_icons.py            (from gpsp/vita)

Needs cairosvg and Pillow.  Writes vstyle_icons.h next to vstyle.c:
  vsi_small / vsi_big   the icons, 8-bit coverage, VSI_COLS x VSI_ROWS cells of
                        VSI_SMALL / VSI_BIG px (two sizes, so neither is drawn
                        far from its own size: no mipmaps on the Vita's path)
  vsi_mark              the wordmark, coverage, VSI_MARK_W x VSI_MARK_H
  vsi_markc             the mark in colour, RGBA, VSI_MARKC square
"""
import io
import os
import sys

import cairosvg
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import vstyle_art as A  # noqa: E402

VITA = os.path.dirname(HERE)
FONTS = os.path.join(VITA, "..", "assets", "fonts")
OUT = os.path.join(VITA, "vstyle_icons.h")

COLS, ROWS = 8, 8
SMALL, BIG = 32, 64
MARK_H = 72
MARKC = 128
WORD = "VitAdhoc"


def coverage(svg, px):
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=px,
                           output_height=px)
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    return im.getchannel("A")


def atlas(cell):
    sheet = Image.new("L", (cell * COLS, cell * ROWS), 0)
    for i in range(len(A.ICONS)):
        sheet.paste(coverage(A.icon_svg(i, cell), cell),
                    ((i % COLS) * cell, (i // COLS) * cell))
    return sheet


def wordmark():
    # Outfit Bold, tracked a little tight; drawn 4x and brought down, so
    # the curves are as smooth as the icons'.
    k = 4
    f = ImageFont.truetype(os.path.join(FONTS, "Outfit-Bold.ttf"),
                           int(MARK_H * 0.98) * k)
    asc, desc = f.getmetrics()
    track = -0.01 * MARK_H * k
    w = 0
    for ch in WORD:
        w += f.getlength(ch) + track
    w = int(w - track + 4 * k)
    im = Image.new("L", (w, (asc + desc)), 0)
    d = ImageDraw.Draw(im)
    x = 2 * k
    for ch in WORD:
        d.text((x, 0), ch, font=f, fill=255)
        x += f.getlength(ch) + track
    bbox = im.getbbox()
    im = im.crop((0, bbox[1] - k, w, bbox[3] + k))
    h = MARK_H
    ww = int(round(im.width * h / im.height))
    return im.resize((ww, h), Image.LANCZOS)


def c_bytes(name, data, per_line=24):
    out = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), per_line):
        out.append("   " + ",".join(str(b) for b in data[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    assert len(A.ICONS) <= COLS * ROWS
    small, big = atlas(SMALL), atlas(BIG)
    mark = wordmark()
    png = cairosvg.svg2png(bytestring=A.mark_svg(MARKC).encode())
    markc = Image.open(io.BytesIO(png)).convert("RGBA")
    # premultiply nothing: vback blends straight alpha
    lines = [
        "/* GENERATED by gpsp/vita/tools/bake_vstyle_icons.py from",
        " * tools/vstyle_art.py -- do not edit.  Icons: %d, in vstyle.h's" % len(A.ICONS),
        " * VS_I_* order.  Wordmark: Outfit Bold (SIL OFL 1.1). */",
        "#ifndef VSTYLE_ICONS_H",
        "#define VSTYLE_ICONS_H",
        "",
        "#define VSI_COLS %d" % COLS,
        "#define VSI_ROWS %d" % ROWS,
        "#define VSI_SMALL %d" % SMALL,
        "#define VSI_BIG %d" % BIG,
        "#define VSI_MARK_W %d" % mark.width,
        "#define VSI_MARK_H %d" % mark.height,
        "#define VSI_MARKC %d" % MARKC,
        "",
        c_bytes("vsi_small", small.tobytes()),
        "",
        c_bytes("vsi_big", big.tobytes()),
        "",
        c_bytes("vsi_mark", mark.tobytes()),
        "",
        c_bytes("vsi_markc", markc.tobytes()),
        "",
        "#endif",
        "",
    ]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (wordmark %dx%d)" % (OUT, mark.width, mark.height))


if __name__ == "__main__":
    main()
