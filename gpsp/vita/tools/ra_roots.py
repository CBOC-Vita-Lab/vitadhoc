#!/usr/bin/env python3
"""Write ra_roots.h: the root certificates ra_http.c hands the Vita's TLS
library (sceHttpsLoadCert) beside the console's own store.

    python3 tools/ra_roots.py /etc/ssl/certs > ra_roots.h

retroachievements.org and media.retroachievements.org are served (October
2026) with Google Trust Services certificates: WR1 -> GTS Root R1 to a
client that offers RSA, WE1 -> GTS Root R4 otherwise.  The rest are the
roots behind most of the web's other certificates, so a change of provider
does not take achievements away with it.  PEM, as the PS3's cellHttps took
them (the Vita's library is that one's descendant)."""
import os
import sys

ROOTS = [
    "GTS_Root_R1", "GTS_Root_R4", "ISRG_Root_X1", "DigiCert_Global_Root_G2",
    "USERTrust_RSA_Certification_Authority", "Amazon_Root_CA_1",
    "GlobalSign_Root_CA_-_R3",
]


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs"
    out = ["/* ra_roots.h -- GENERATED by tools/ra_roots.py; do not edit.",
           " * Root certificates for RetroAchievements' servers (ra_http.c). */",
           "#ifndef RA_ROOTS_H", "#define RA_ROOTS_H", ""]
    names = []
    for r in ROOTS:
        pem = open(os.path.join(d, r + ".pem")).read().strip() + "\n"
        if not pem.startswith("-----BEGIN CERTIFICATE-----"):
            sys.exit(r + ": not one PEM certificate")
        ident = "ra_root_" + "".join(c if c.isalnum() else "_" for c in r)
        names.append(ident)
        out.append("/* %s */" % r)
        out.append("static const char %s[] =" % ident)
        for line in pem.splitlines():
            out.append('   "%s\\n"' % line)
        out.append(";")
        out.append("")
    out.append("static const char *const ra_roots[] = {")
    out += ["   %s," % n for n in names]
    out.append("};")
    out.append("static const unsigned ra_root_sizes[] = {")
    out += ["   sizeof(%s) - 1," % n for n in names]
    out.append("};")
    out.append("#define RA_ROOTS_N %d" % len(names))
    out.append("")
    out.append("#endif")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
