/*
 * Generator for playerkit/src/pk_font_data.cpp: rasterises printable ASCII of
 * Inter (caption, body, label) and Outfit (sub, title) at the sizes the
 * VitAdhoc interface uses, packs each face into an A8 atlas and writes them
 * as zero-run-length-coded byte arrays. Developer tool, not part of any
 * player. Uses stb_truetype (public domain) only to rasterise.
 *
 *   make -C playerkit regen-font
 *
 * Copyright CBOC-Vita. MIT licence (see playerkit/LICENSE). The glyph bitmaps
 * written are derived from fonts under the SIL Open Font License 1.1
 * (playerkit/fonts/).
 */
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <vector>
#include <string>

static std::vector<unsigned char> slurp(const std::string &p)
{
	std::vector<unsigned char> v;
	FILE *f = fopen(p.c_str(), "rb");
	if (!f) { fprintf(stderr, "cannot read %s\n", p.c_str()); exit(1); }
	unsigned char b[65536];
	size_t n;
	while ((n = fread(b, 1, sizeof b, f)) > 0) v.insert(v.end(), b, b + n);
	fclose(f);
	return v;
}

struct FaceSpec { const char *font; float px; int atlas_w; };

struct G { int ax, ay, w, h, ox, oy; float adv; };

int main(int argc, char **argv)
{
	if (argc < 3) { fprintf(stderr, "usage: gen_font fontdir out.cpp\n"); return 1; }
	std::string dir = argv[1];
	const FaceSpec faces[5] = {
		{ "Inter-Regular.ttf", 20.0f, 256 },     /* F_CAPTION */
		{ "Inter-Regular.ttf", 24.0f, 256 },     /* F_BODY    */
		{ "Inter-SemiBold.ttf", 24.0f, 256 },    /* F_LABEL   */
		{ "Outfit-Medium.ttf", 30.0f, 256 },     /* F_SUB     */
		{ "Outfit-SemiBold.ttf", 40.0f, 256 }    /* F_TITLE   */
	};
	FILE *out = fopen(argv[2], "wb");
	if (!out) return 1;
	fprintf(out, "/* GENERATED by playerkit/tools/gen_font.cpp. Do not edit.\n"
	             " * Glyph bitmaps rasterised from Inter and Outfit (SIL Open Font License 1.1,\n"
	             " * see playerkit/fonts/). The glyph shapes belong to their font authors. */\n"
	             "#include \"pk_gfx.h\"\n#include <string.h>\n#include <stdlib.h>\n\nnamespace pk {\nnamespace {\n\n");
	int aw[5], ah[5], lh[5], asc[5];
	for (int f = 0; f < 5; f++) {
		std::vector<unsigned char> ttf = slurp(dir + "/" + faces[f].font);
		stbtt_fontinfo info;
		if (!stbtt_InitFont(&info, ttf.data(), stbtt_GetFontOffsetForIndex(ttf.data(), 0))) { fprintf(stderr, "bad font\n"); return 1; }
		float sc = stbtt_ScaleForMappingEmToPixels(&info, faces[f].px);
		int a, d, gap;
		stbtt_GetFontVMetrics(&info, &a, &d, &gap);
		asc[f] = (int) ceilf(a * sc);
		lh[f] = (int) ceilf((a - d + gap) * sc);
		int W = faces[f].atlas_w;
		/* shelf packing, 1 px gutters */
		std::vector<G> gl(95);
		std::vector<std::vector<unsigned char> > bm(95);
		int px = 1, py = 1, rowh = 0;
		for (int c = 32; c <= 126; c++) {
			int x0, y0, x1, y1;
			stbtt_GetCodepointBitmapBox(&info, c, sc, sc, &x0, &y0, &x1, &y1);
			int w = x1 - x0, h = y1 - y0, adv_i, lsb;
			stbtt_GetCodepointHMetrics(&info, c, &adv_i, &lsb);
			G &g = gl[c - 32];
			g.w = w; g.h = h; g.ox = x0; g.oy = asc[f] + y0;
			g.adv = adv_i * sc;
			bm[c - 32].assign((size_t) (w > 0 && h > 0 ? w * h : 0), 0);
			if (w > 0 && h > 0) stbtt_MakeCodepointBitmap(&info, bm[c - 32].data(), w, h, w, sc, sc, c);
			if (px + w + 1 > W) { px = 1; py += rowh + 1; rowh = 0; }
			g.ax = px; g.ay = py;
			px += w + 1;
			if (h > rowh) rowh = h;
		}
		int H = py + rowh + 1;
		aw[f] = W; ah[f] = H;
		std::vector<unsigned char> atlas((size_t) W * H, 0);
		for (int i = 0; i < 95; i++)
			for (int y = 0; y < gl[i].h; y++)
				memcpy(&atlas[(size_t) (gl[i].ay + y) * W + gl[i].ax], &bm[i][(size_t) y * gl[i].w], (size_t) gl[i].w);
		/* zero-run-length coding: a 0 byte is followed by the run length - 1 (0..255) */
		std::vector<unsigned char> rle;
		for (size_t i = 0; i < atlas.size();) {
			if (atlas[i] != 0) { rle.push_back(atlas[i]); i++; continue; }
			size_t j = i;
			while (j < atlas.size() && atlas[j] == 0 && j - i < 256) j++;
			rle.push_back(0);
			rle.push_back((unsigned char) (j - i - 1));
			i = j;
		}
		fprintf(out, "const unsigned char kRle%d[] = {", f);
		for (size_t i = 0; i < rle.size(); i++) fprintf(out, "%s%u,", (i % 32) ? "" : "\n", rle[i]);
		fprintf(out, "\n};\n");
		fprintf(out, "const Glyph kGlyph%d[95] = {\n", f);
		for (int i = 0; i < 95; i++)
			fprintf(out, "{%d,%d,%d,%d,%d,%d,%.3ff},%s", gl[i].ax, gl[i].ay, gl[i].w, gl[i].h, gl[i].ox, gl[i].oy, gl[i].adv, (i % 4 == 3) ? "\n" : "");
		fprintf(out, "};\n\n");
		fprintf(stderr, "face %d: %s %.0fpx atlas %dx%d, %zu bytes coded\n", f, faces[f].font, faces[f].px, W, H, rle.size());
		(void) lh;
	}
	fprintf(out, "struct Packed { const unsigned char *rle; size_t rle_len; const Glyph *g; int w, h, line_h, ascent; };\n"
	             "const Packed kPacked[5] = {\n");
	for (int f = 0; f < 5; f++)
		fprintf(out, "{kRle%d, sizeof kRle%d, kGlyph%d, %d, %d, %d, %d},\n", f, f, f, aw[f], ah[f], lh[f], asc[f]);
	fprintf(out, "};\n\nFaceData g_face[5];\nunsigned char *g_pix[5];\nbool g_ready[5];\n\n"
	             "}  // namespace\n\n"
	             "const FaceData *builtin_face(int face)\n{\n"
	             "\tif (face < 0 || face >= 5) return 0;\n"
	             "\tif (!g_ready[face]) {\n"
	             "\t\tconst Packed &p = kPacked[face];\n"
	             "\t\tunsigned char *pix = (unsigned char *) calloc((size_t) p.w * p.h, 1);\n"
	             "\t\tif (!pix) return 0;\n"
	             "\t\tsize_t o = 0;\n"
	             "\t\tfor (size_t i = 0; i < p.rle_len && o < (size_t) p.w * p.h;) {\n"
	             "\t\t\tif (p.rle[i] != 0) { pix[o++] = p.rle[i++]; continue; }\n"
	             "\t\t\tsize_t run = (size_t) p.rle[i + 1] + 1;\n"
	             "\t\t\to += run;\n"
	             "\t\t\ti += 2;\n"
	             "\t\t}\n"
	             "\t\tg_pix[face] = pix;\n"
	             "\t\tFaceData &fd = g_face[face];\n"
	             "\t\tfd.atlas = pix; fd.atlas_w = p.w; fd.atlas_h = p.h; fd.line_h = p.line_h; fd.ascent = p.ascent;\n"
	             "\t\tfor (int i = 0; i < 95; i++) fd.g[i] = p.g[i];\n"
	             "\t\tg_ready[face] = true;\n"
	             "\t}\n"
	             "\treturn &g_face[face];\n}\n\n}  // namespace pk\n");
	fclose(out);
	return 0;
}
