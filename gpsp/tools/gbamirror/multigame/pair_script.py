#!/usr/bin/env python3
"""pair_script.py SPEC HOST_OUT JOIN_OUT -- one fixture spec, two autopilot
scripts that stay frame-aligned.

A spec line is an ordinary fe_autopilot line, optionally prefixed:
  H <line>   host's machine only (slot 0, the parent)
  J <line>   join's machine only (slot 1)
  (none)     both
  B <host line> || <join line>   both machines at once, different input
             (both halves must take the same frames, or the longer one's
             excess goes to the other side as a wait)
The other side gets the same number of frames as a `wait` (press X N is
N + 2 frames: the engine's release gap; hold X N is N), so the two scripts
reach every later line on the same frame.  A prefixed RAM-gated
line (waitram, holdmash, ...) gets no counterpart: it takes as long as the
game does, so put a RAM-gated step on both sides after it to re-align.
Comments and blank lines pass through to both."""
import sys

PRESS_GAP = 2   # fe_autopilot.c AP_PRESS_GAP


def frames(tok):
    op = tok[0]
    if op == "press":
        return (int(tok[2]) if len(tok) > 2 else 2) + PRESS_GAP
    if op == "hold":
        return int(tok[2])
    if op == "wait":
        return int(tok[1])
    if op in ("dump", "evt", "logram", "logptr", "logbytes"):
        return 0
    # a RAM-gated step takes as long as the game does: the other side gets
    # nothing, and the next RAM-gated step on both re-aligns them
    return 0


def main():
    spec, ho, jo = sys.argv[1:4]
    H, J = [], []
    for raw in open(spec, encoding="utf-8"):
        ln = raw.rstrip("\n")
        s = ln.strip()
        if s[:2] == "B ":
            h, j = (x.strip() for x in s[2:].split("||"))
            nh, nj = frames(h.split()), frames(j.split())
            H.append(h)
            J.append(j)
            if nh > nj:
                J.append("wait %d" % (nh - nj))
            elif nj > nh:
                H.append("wait %d" % (nj - nh))
        elif s[:2] in ("H ", "J "):
            side, body = s[0], s[2:].strip()
            n = frames(body.split())
            mine, other = (H, J) if side == "H" else (J, H)
            mine.append(body)
            if n:
                other.append("wait %d" % n)
        else:
            H.append(ln)
            J.append(ln)
    hdr = "# generated by pair_script.py from %s -- edit the spec, not this\n" % spec.split("/")[-1]
    open(ho, "w", newline="\n").write(hdr + "\n".join(H) + "\n")
    open(jo, "w", newline="\n").write(hdr + "\n".join(J) + "\n")


if __name__ == "__main__":
    main()
